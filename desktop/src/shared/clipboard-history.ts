/**
 * The launcher's clipboard history: off until somebody turns it on, kept in
 * memory only (never written to disk, never sent anywhere), at most
 * `CLIPBOARD_LIMIT` entries, and blind to what a password manager marks as
 * not for history.
 *
 * The marks are the platforms' own conventions:
 * - Windows: a copy carrying `ExcludeClipboardContentFromMonitorProcessing`, or
 *   `CanIncludeInClipboardHistory` set to a DWORD of 0, is kept out of the
 *   system's own history (https://learn.microsoft.com/windows/win32/dataxchg/clipboard-formats#cloud-clipboard-and-clipboard-history-formats).
 * - macOS: `org.nspasteboard.ConcealedType`, `TransientType` and
 *   `AutoGeneratedType` (http://nspasteboard.org).
 * - Linux: KDE's `x-kde-passwordManagerHint` with the value `secret`, which
 *   KeePassXC sets as well.
 */

export const CLIPBOARD_LIMIT = 200;

/** The longest copy kept, in characters; anything longer is a file's worth
 *  nobody pastes back from a launcher. */
export const CLIPBOARD_MAX_CHARS = 20_000;

/** How the platform's clipboard is asked, so the rules run without one. */
export interface ClipboardProbe {
    has(format: string): Promise<boolean>;
    /** The raw bytes of a format, or null when they cannot be read. */
    read(format: string): Promise<Uint8Array | null>;
}

const CONCEALED: Readonly<Partial<Record<NodeJS.Platform, readonly string[]>>> = {
    win32: ["ExcludeClipboardContentFromMonitorProcessing"],
    darwin: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
};

/** Whether the copy on the clipboard is marked as not for history. */
export async function isConcealed(platform: NodeJS.Platform, probe: ClipboardProbe): Promise<boolean> {
    for (const format of CONCEALED[platform] ?? []) if (await probe.has(format)) return true;
    if (platform === "win32" && (await probe.has("CanIncludeInClipboardHistory"))) {
        const value = await probe.read("CanIncludeInClipboardHistory");
        // A DWORD; zero means "keep out". Anything unreadable is kept out too.
        if (!value || value.length < 4) return true;
        if (value[0] === 0 && value[1] === 0 && value[2] === 0 && value[3] === 0) return true;
    }
    if (platform === "linux" && (await probe.has("x-kde-passwordManagerHint"))) {
        const value = await probe.read("x-kde-passwordManagerHint");
        if (!value || new TextDecoder().decode(value).trim() === "secret") return true;
    }
    return false;
}

export interface ClipEntry {
    readonly text: string;
    readonly at: number;
}

/**
 * The history with `text` on top: a copy already in it moves up instead of
 * appearing twice, blank and over-long copies are not kept, and the oldest
 * fall off past the limit.
 */
export function withClip(history: readonly ClipEntry[], text: string, at: number, limit = CLIPBOARD_LIMIT): readonly ClipEntry[] {
    if (!text.trim() || text.length > CLIPBOARD_MAX_CHARS) return history;
    if (history[0]?.text === text) return history;
    return [{ text, at }, ...history.filter((entry) => entry.text !== text)].slice(0, limit);
}
