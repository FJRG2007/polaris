export const YOUTUBE_TARGETS = {
    moderate: "restrictmoderate.youtube.com",
    strict: "restrict.youtube.com"
} as const;

/** Each host and the locked host it answers as, for the chosen settings. */
export function safeSearchAliases(input: {
    readonly safeSearch: boolean;
    readonly youtube: "off" | "moderate" | "strict";
}): { name: string; target: string }[] {
    const aliases: { name: string; target: string }[] = [];
    if (input.safeSearch) {
        for (const domain of GOOGLE_DOMAINS)
            aliases.push({ name: `www.${domain}`, target: "forcesafesearch.google.com" });
        for (const host of BING_HOSTS) aliases.push({ name: host, target: "strict.bing.com" });
    }
    if (input.youtube !== "off")
        for (const host of YOUTUBE_HOSTS)
            aliases.push({ name: host, target: YOUTUBE_TARGETS[input.youtube] });
    return aliases;
}
