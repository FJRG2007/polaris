/**
 * Generate a SQLite variant of the Prisma schema for local, container-free dev.
 * The models are already SQLite-portable, so this only swaps the datasource
 * provider; keeping it generated (rather than a second hand-maintained file)
 * means the dev schema can never drift from the Postgres source of truth.
 */

import { dirname, join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const prismaDir = join(here, "..", "packages", "db", "prisma");

/** Rewrite the Postgres schema source into its SQLite equivalent. */
export function toSqliteSchema(source) {
    return (
        source
            .replace(
                /datasource db \{[^}]*\}/,
                'datasource db {\n    provider = "sqlite"\n    url      = env("POLARIS_DATABASE_URL")\n}'
            )
            // SQLite has no native uuid type; drop the Postgres-only @db.Uuid mapping so
            // the id columns fall back to TEXT (the uuid string is generated by uuid(7)).
            .replace(/ @db\.Uuid/g, "")
            // SQLite has no lists of scalars, which Prisma refuses outright. Store any
            // such column as Json instead: the client still reads and writes an array.
            .replace(
                /^(\s+\w+\s+)(?:String|Int|BigInt|Float|Decimal|Boolean|DateTime|Bytes)\[\](.*)$/gm,
                (_, field, rest) => `${field}Json${rest.replace("@default([])", '@default("[]")')}`
            )
            // Prisma accepts a Json default for SQLite but writes it into the table
            // unquoted (`DEFAULT {}`), which SQLite rejects and `db push` fails on.
            // Spell it as the quoted SQL literal the column should get instead.
            .replace(
                /^(\s+\w+\s+Json\??\s.*)@default\("([^"]*)"\)/gm,
                (_, head, value) => `${head}@default(dbgenerated("'${value.replaceAll("'", "''")}'"))`
            )
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const source = readFileSync(join(prismaDir, "schema.prisma"), "utf8");
    // enigma:allow-sqlite - this variant is never the deployed datastore. Polaris
    // runs on Postgres; this exists so a contributor can work without standing up a
    // database container, and is generated from that Postgres schema every time.
    const banner = `// AUTO-GENERATED from schema.prisma by scripts/gen-sqlite-schema.mjs - do not edit.
// enigma:allow-sqlite - container-free local dev only; Polaris deploys on Postgres.
`;
    writeFileSync(join(prismaDir, "schema.sqlite.prisma"), banner + toSqliteSchema(source));
    console.log("Wrote packages/db/prisma/schema.sqlite.prisma");
}
