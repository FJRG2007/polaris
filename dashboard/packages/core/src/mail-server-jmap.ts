/**
 * Leave bootstrap mode: name the server and its first domain.
 *
 * A fresh engine starts in bootstrap mode, serving only the management API and
 * the `Bootstrap` singleton. Setting it writes the configuration, provisions
 * the rest and restarts into normal service. The certificate is requested from
 * Let's Encrypt and the first domain's DKIM keys are generated by the engine
 * itself, which is what makes its published key and its signing key the same.
 */
export function bootstrapCall(input: { hostname: string; domain: string }): JmapCall {
    return [
        "x:Bootstrap/set",
        {
            update: {
                singleton: {
                    serverHostname: input.hostname,
                    defaultDomain: input.domain,
                    requestTlsCertificate: true,
                    generateDkimKeys: true
                }
            }
        },
        "bootstrap"
    ];
}

