/** Something the engine refused, in its own words. */
export class StalwartRefusal extends Error {
    public constructor(
        message: string,
        public readonly type: string
    ) {
        super(message);
        this.name = "StalwartRefusal";
    }
}

/** The arguments of the answer to one call, or the engine's refusal of it. */
export function answerOf(response: unknown, callId: string): Record<string, unknown> {
    const responses =
        response && typeof response === "object" && Array.isArray((response as { methodResponses?: unknown }).methodResponses)
            ? ((response as { methodResponses: unknown[] }).methodResponses as unknown[])
            : [];
    for (const entry of responses) {
        if (!Array.isArray(entry) || entry[2] !== callId) continue;
        const [name, args] = entry as [string, Record<string, unknown>];
        if (name === "error") {
            const type = typeof args?.type === "string" ? args.type : "error";
            const description = typeof args?.description === "string" ? args.description : type;
            throw new StalwartRefusal(description, type);
        }
        return args ?? {};
    }
    throw new StalwartRefusal("The mail server did not answer that request", "missing");
}

/** The id the engine gave something just created, or its reason for refusing. */
export function createdId(response: unknown, callId: string, key: string): string {
    const answer = answerOf(response, callId);
    const created = (answer.created as Record<string, { id?: unknown }> | undefined)?.[key];
    if (created && typeof created.id === "string") return created.id;
    throw setRefusal((answer.notCreated as Record<string, unknown> | undefined)?.[key], "create");
}

/** Throw the reason an update or a destroy was refused, if it was. */
export function assertApplied(response: unknown, callId: string, id: string): void {
    const answer = answerOf(response, callId);
    const refused =
        (answer.notUpdated as Record<string, unknown> | undefined)?.[id] ??
        (answer.notDestroyed as Record<string, unknown> | undefined)?.[id];
    if (refused) throw setRefusal(refused, "update");
}

function setRefusal(error: unknown, verb: string): StalwartRefusal {
    const shape = (error ?? {}) as { type?: unknown; description?: unknown; properties?: unknown };
    const type = typeof shape.type === "string" ? shape.type : "invalidProperties";
    const properties = Array.isArray(shape.properties) ? ` (${shape.properties.join(", ")})` : "";
    const description =
        typeof shape.description === "string" && shape.description
            ? shape.description
            : `The mail server would not ${verb} that`;
    return new StalwartRefusal(`${description}${properties}`, type);
}

/** The objects a `/get` answered with. */
export function listOfAnswer<T>(response: unknown, callId: string): T[] {
    const answer = answerOf(response, callId);
    return Array.isArray(answer.list) ? (answer.list as T[]) : [];
}
