/**
 * Create a domain. DKIM keys are the engine's to generate and rotate; DNS stays
 * manual on its side because Polaris is the one that publishes the records -
 * through the operator's own DNS integration, with a plan they can read first.
 */
export function domainCreateCall(name: string): JmapCall {
    return [
        "x:Domain/set",
        {
            create: {
                domain: {
                    name,
                    aliases: {},
                    certificateManagement: { "@type": "Manual" },
                    dkimManagement: { "@type": "Automatic" },
                    dnsManagement: { "@type": "Manual" },
                    subAddressing: { "@type": "Enabled" }
                }
            }
        },
        "domain"
    ];
}

/** Every domain, with what the screens show and the zone the engine expects. */
export function domainListCalls(): JmapCall[] {
    return [
        ["x:Domain/query", {}, "q"],
        [
            "x:Domain/get",
            {
                "#ids": { resultOf: "q", name: "x:Domain/query", path: "/ids" },
                properties: ["id", "name", "isEnabled", "catchAllAddress", "dnsZoneFile", "reportAddressUri"]
            },
            "domains"
        ]
    ];
}

/** Route mail for unknown addresses at a domain to one address, or stop. */
export function domainCatchAllCall(domainId: string, address: string | null): JmapCall {
    return ["x:Domain/set", { update: { [domainId]: { catchAllAddress: address } } }, "catchall"];
}

export function domainDestroyCall(domainId: string): JmapCall {
    return ["x:Domain/set", { destroy: [domainId] }, "destroy"];
}

/**
 * Where a domain's DMARC, TLS-RPT and CAA reports are sent. The engine writes
 * this address into the `rua` of the DMARC and TLS-RPT records it generates, so
 * it has to be an address at the same domain: a report address at another
 * domain is only honoured by receivers when that domain publishes an
 * authorization record for it (RFC 7489 section 7.1).
 */
export function domainReportAddressCall(domainId: string, address: string): JmapCall {
    return ["x:Domain/set", { update: { [domainId]: { reportAddressUri: `mailto:${address}` } } }, "reports"];
}

