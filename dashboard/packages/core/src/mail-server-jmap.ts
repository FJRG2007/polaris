/** One password credential, in the engine's credential variant. */
function passwordCredential(secret: string): Record<string, unknown> {
    return { "@type": "Password", secret };
}

export interface MailboxCreate {
    readonly name: string;
    readonly domainId: string;
    readonly password: string;
    /** Bytes; null leaves the account without a disk quota. */
    readonly quotaBytes: number | null;
    /** An administrator of the mail server itself - only ever the account
     *  Polaris manages it with. */
    readonly admin?: boolean;
    readonly description?: string;
}

/** Create a mailbox: a `User` account with one password. */
export function accountCreateCall(input: MailboxCreate): JmapCall {
    return [
        "x:Account/set",
        {
            create: {
                account: {
                    "@type": "User",
                    name: input.name,
                    domainId: input.domainId,
                    aliases: {},
                    credentials: listOf([passwordCredential(input.password)]),
                    encryptionAtRest: { "@type": "Disabled" },
                    memberGroupIds: {},
                    permissions: { "@type": "Inherit" },
                    quotas: input.quotaBytes !== null ? { maxDiskQuota: input.quotaBytes } : {},
                    roles: { "@type": input.admin ? "Admin" : "User" },
                    ...(input.description ? { description: input.description } : {})
                }
            }
        },
        "account"
    ];
}

export function accountListCalls(): JmapCall[] {
    return [
        ["x:Account/query", {}, "q"],
        [
            "x:Account/get",
            {
                "#ids": { resultOf: "q", name: "x:Account/query", path: "/ids" },
                properties: ["id", "name", "domainId", "emailAddress", "aliases", "quotas", "description", "roles"]
            },
            "accounts"
        ]
    ];
}

/** Replace a mailbox's password. The list is replaced whole, which is the point:
 *  the old password stops working the moment this lands. */
export function accountPasswordCall(accountId: string, password: string): JmapCall {
    return [
        "x:Account/set",
        { update: { [accountId]: { credentials: listOf([passwordCredential(password)]) } } },
        "password"
    ];
}

export function accountQuotaCall(accountId: string, quotaBytes: number | null): JmapCall {
    return [
        "x:Account/set",
        { update: { [accountId]: { quotas: quotaBytes !== null ? { maxDiskQuota: quotaBytes } : {} } } },
        "quota"
    ];
}

/** Replace a mailbox's aliases with this list. */
export function accountAliasesCall(
    accountId: string,
    aliases: readonly { name: string; domainId: string }[]
): JmapCall {
    return [
        "x:Account/set",
        {
            update: {
                [accountId]: {
                    aliases: listOf(aliases.map((alias) => ({ enabled: true, name: alias.name, domainId: alias.domainId })))
                }
            }
        },
        "aliases"
    ];
}

export function accountDestroyCall(accountId: string): JmapCall {
    return ["x:Account/set", { destroy: [accountId] }, "destroy"];
}

