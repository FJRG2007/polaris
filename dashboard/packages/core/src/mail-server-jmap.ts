/** What the relay route is called, so it can be found and replaced. */
export const RELAY_ROUTE_NAME = "polaris-relay";

/** The route the engine delivers through when no relay is set: straight to the
 *  recipient's MX. */
export const DIRECT_ROUTE_NAME = "mx";

export interface RelayRoute {
    readonly host: string;
    readonly port: number;
    /** TLS from the first byte (465) rather than STARTTLS. */
    readonly implicitTls: boolean;
    readonly username: string;
    readonly secret: string;
}

/** Create the relay route every outbound message is sent through. */
export function relayRouteCreateCall(relay: RelayRoute): JmapCall {
    return [
        "x:MtaRoute/set",
        {
            create: {
                relay: {
                    "@type": "Relay",
                    name: RELAY_ROUTE_NAME,
                    address: relay.host,
                    port: relay.port,
                    protocol: "smtp",
                    implicitTls: relay.implicitTls,
                    allowInvalidCerts: false,
                    authUsername: relay.username,
                    authSecret: relay.secret ? { "@type": "Value", secret: relay.secret } : { "@type": "None" }
                }
            }
        },
        "route"
    ];
}

export function routeListCall(): JmapCall[] {
    return [
        ["x:MtaRoute/query", {}, "q"],
        [
            "x:MtaRoute/get",
            { "#ids": { resultOf: "q", name: "x:MtaRoute/query", path: "/ids" }, properties: ["id", "name"] },
            "routes"
        ]
    ];
}

export function routeDestroyCall(routeId: string): JmapCall {
    return ["x:MtaRoute/set", { destroy: [routeId] }, "destroy"];
}

/**
 * Choose the route every queued message leaves by. The strategy's `route` is an
 * expression; with no conditions it is its `else`, a quoted route name.
 */
export function outboundRouteCall(routeName: string): JmapCall {
    if (!/^[a-z0-9-]+$/.test(routeName)) throw new Error("not a route name");
    return [
        "x:MtaOutboundStrategy/set",
        { update: { singleton: { route: { else: `'${routeName}'` } } } },
        "strategy"
    ];
}

