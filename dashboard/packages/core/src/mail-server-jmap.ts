/** The events a webhook asks for: every message the server takes in, and which
 *  of the two its spam filter decided it was. */
export const INBOUND_EVENTS = ["message-ingest.ham", "message-ingest.spam"] as const;

/** Tell the engine to post incoming-mail events to Polaris, signed. */
export function webhookCreateCall(url: string, signingSecret: string): JmapCall {
    return [
        "x:WebHook/set",
        {
            create: {
                hook: {
                    url,
                    events: setOf(INBOUND_EVENTS),
                    eventsPolicy: "include",
                    signatureKey: { "@type": "Value", secret: signingSecret },
                    httpAuth: { "@type": "Unauthenticated" }
                }
            }
        },
        "webhook"
    ];
}

