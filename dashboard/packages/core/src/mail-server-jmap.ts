/**
 * The requests Polaris sends to the mail server it runs, as pure values.
 *
 * The engine is Stalwart (v0.16). From that version every administrative action
 * is a JMAP object behind the same `/jmap` endpoint that serves mail: a domain is
 * `x:Domain`, a mailbox is an `x:Account` of type `User`, a forward is an
 * `x:MailingList`, the outbound relay is an `x:MtaRoute`, and so on, each with the
 * standard `/get`, `/set` and `/query` methods under the `urn:stalwart:jmap`
 * capability. Everything here is built from the engine's own schema reference
 * (stalw.art/docs/ref/object) - no field is guessed.
 *
 * Three encodings in that schema differ from plain JSON and are the whole reason
 * these builders exist rather than object literals at the call site:
 *
 * - a list is an object keyed by stringified positions (`{"0": ..., "1": ...}`),
 * - a set is an object mapping each member to `true`,
 * - a variant is an object with an `@type` naming it.
 *
 * Kept pure so the exact bytes that reach the engine are asserted in a test.
 */

/** The capabilities every management request declares. */
export const STALWART_JMAP_USING = ["urn:ietf:params:jmap:core", "urn:stalwart:jmap"] as const;

/** One JMAP method call: its name, its arguments, and the id its answer comes
 *  back under. */
export type JmapCall = readonly [string, Record<string, unknown>, string];

/** A whole request. */
export interface JmapRequest {
    readonly using: readonly string[];
    readonly methodCalls: readonly JmapCall[];
}

export function jmapRequest(calls: readonly JmapCall[]): JmapRequest {
    return { using: [...STALWART_JMAP_USING], methodCalls: calls };
}

/** The engine's list encoding: positions as string keys. */
export function listOf<T>(items: readonly T[]): Record<string, T> {
    const out: Record<string, T> = {};
    items.forEach((item, index) => {
        out[String(index)] = item;
    });
    return out;
}

/** The engine's set encoding: every member mapped to `true`. */
export function setOf(values: readonly string[]): Record<string, true> {
    const out: Record<string, true> = {};
    for (const value of values) out[value] = true;
    return out;
}

/** Read a list the engine sent back, in position order, whichever encoding it
 *  arrived in. */
export function fromList<T>(value: unknown): T[] {
    if (Array.isArray(value)) return value as T[];
    if (!value || typeof value !== "object") return [];
    return Object.entries(value as Record<string, T>)
        .sort(([left], [right]) => Number(left) - Number(right))
        .map(([, item]) => item);
}

/** Read a set the engine sent back as its members. */
export function fromSet(value: unknown): string[] {
    if (Array.isArray(value)) return value.filter((item): item is string => typeof item === "string");
    if (!value || typeof value !== "object") return [];
    return Object.entries(value as Record<string, unknown>)
        .filter(([, member]) => member === true)
        .map(([key]) => key);
}

