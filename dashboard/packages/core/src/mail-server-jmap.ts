/** The capabilities a request about somebody's mail declares. */
export const JMAP_MAIL_USING = ["urn:ietf:params:jmap:core", "urn:ietf:params:jmap:mail"] as const;

export function jmapMailRequest(calls: readonly JmapCall[]): JmapRequest {
    return { using: [...JMAP_MAIL_USING], methodCalls: calls };
}

/**
 * The oldest messages not read yet, with their attachments. Read in batches and
 * marked seen as they are handled, so a mailbox that has collected a year of
 * reports is worked through over several runs rather than in one.
 */
export function unreadWithAttachmentsCalls(accountId: string, limit: number): JmapCall[] {
    return [
        [
            "Email/query",
            {
                accountId,
                filter: { notKeyword: "$seen" },
                sort: [{ property: "receivedAt", isAscending: true }],
                limit
            },
            "q"
        ],
        [
            "Email/get",
            {
                accountId,
                "#ids": { resultOf: "q", name: "Email/query", path: "/ids" },
                properties: ["id", "receivedAt", "attachments"]
            },
            "messages"
        ]
    ];
}

export function markSeenCall(accountId: string, emailIds: readonly string[]): JmapCall {
    const update: Record<string, Record<string, boolean>> = {};
    for (const id of emailIds) update[id] = { "keywords/$seen": true };
    return ["Email/set", { accountId, update }, "seen"];
}

/**
 * A blob's download path, from the session's `downloadUrl` template (RFC 8620
 * section 2): `{accountId}`, `{blobId}`, `{type}` and `{name}`, each
 * percent-encoded. Only the path and query are kept; the host in the template
 * is the public name, and the request goes over the management endpoint.
 */
export function downloadPath(
    template: string,
    values: { accountId: string; blobId: string; type: string; name: string }
): string {
    const expanded = template.replace(/\{(accountId|blobId|type|name)\}/g, (_, key: keyof typeof values) =>
        encodeURIComponent(values[key])
    );
    const url = new URL(expanded, "http://engine");
    return `${url.pathname}${url.search}`;
}

