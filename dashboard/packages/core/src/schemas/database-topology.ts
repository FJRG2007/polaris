/**
 * The `mysqld` arguments a member of a replicated MySQL starts with: a server id
 * of its own (the primary 1, replicas from 2), and GTIDs on, which the manual
 * requires of source and replica alike. Binary logging is on by default.
 *
 * Replicas are not started with `read_only`: the image's first start runs its
 * setup through a temporary server given these same arguments, and a read-only
 * server refuses that setup. They are made read-only once they follow the
 * primary - see `mysqlFollowCommands`.
 */
export function mysqlMemberCommand(serverId: number): string[] {
    if (!Number.isInteger(serverId) || serverId < 1 || serverId > 4_294_967_295) throw new Error("A server id is a positive integer");
    return ["mysqld", `--server-id=${serverId}`, "--gtid-mode=ON", "--enforce-gtid-consistency=ON"];
}

/** A SQL string literal for a value that has already been checked to hold no
 *  quote or backslash. */
function sqlLiteral(value: string): string {
    if (/['\\]/.test(value)) throw new Error("A value with a quote or a backslash cannot be written into a statement");
    return `'${value}'`;
}

/**
 * The replication account on the primary, created or brought back to the
 * stored password, with the one privilege a replica needs. The statements are
 * written to the primary's binary log, so the replicas get the account too.
 */
export function mysqlReplicationUserCommand(rootPassword: string, replicationPassword: string): MaintenanceCommand {
    const account = `${sqlLiteral(MYSQL_REPLICATION_USER)}@'%'`;
    const secret = sqlLiteral(replicationPassword);
    return {
        argv: [
            "mysql",
            "-uroot",
            `-p${rootPassword}`,
            "-e",
            `CREATE USER IF NOT EXISTS ${account} IDENTIFIED BY ${secret}; ALTER USER ${account} IDENTIFIED BY ${secret}; GRANT REPLICATION SLAVE ON *.* TO ${account};`
        ],
        describe: "Creating the replication account"
    };
}

/**
 * Point a replica at its primary and start it following.
 *
 * `SOURCE_AUTO_POSITION = 1` is GTID replication: the replica asks for every
 * transaction it has not applied, which on a new, empty replica is everything
 * the primary has logged - its database, its accounts and its data. A
 * replication account uses `caching_sha2_password`, which the manual says needs
 * an encrypted connection or the source's public key: `SOURCE_SSL = 1` asks for
 * the first, over the certificate the server generates for itself, and
 * `GET_SOURCE_PUBLIC_KEY = 1` allows the second. `STOP REPLICA` first, because
 * the source can only be changed with both replication threads stopped - which
 * is also what makes this safe to run again.
 *
 * `super_read_only` last, persisted so a restart keeps it: nothing but
 * replication writes to a replica. It implies `read_only`.
 */
export function mysqlFollowCommands(
    rootPassword: string,
    primaryHost: string,
    replicationPassword: string
): MaintenanceCommand[] {
    checkHost(primaryHost);
    const run = (sql: string, describe: string): MaintenanceCommand => ({
        argv: ["mysql", "-uroot", `-p${rootPassword}`, "-e", sql],
        describe
    });
    return [
        run(
            [
                "STOP REPLICA;",
                `CHANGE REPLICATION SOURCE TO SOURCE_HOST = ${sqlLiteral(primaryHost)}, SOURCE_PORT = ${MYSQL_PORT},`,
                `SOURCE_USER = ${sqlLiteral(MYSQL_REPLICATION_USER)}, SOURCE_PASSWORD = ${sqlLiteral(replicationPassword)},`,
                "SOURCE_AUTO_POSITION = 1, SOURCE_SSL = 1, GET_SOURCE_PUBLIC_KEY = 1;",
                "START REPLICA;"
            ].join(" "),
            "Following the primary"
        ),
        run("SET PERSIST super_read_only = ON;", "Making the replica read-only")
    ];
}

/** A replica's replication state, printed vertically. */
export function mysqlReplicaStatusCommand(rootPassword: string): MaintenanceCommand {
    return {
        argv: ["mysql", "-uroot", `-p${rootPassword}`, "-e", "SHOW REPLICA STATUS\\G"],
        describe: "Reading the replica's state"
    };
}

/** What `SHOW REPLICA STATUS\G` said: whether both threads run, how far behind
 *  the replica is, and the last error either thread hit. */
export function parseReplicaStatus(output: string): {
    following: boolean;
    lagSeconds: number | null;
    error: string | null;
} {
    const field = (key: string): string | undefined => {
        const line = output.split(/\r?\n/).find((entry) => entry.trim().startsWith(`${key}:`));
        return line?.slice(line.indexOf(":") + 1).trim();
    };
    const lag = Number.parseInt(field("Seconds_Behind_Source") ?? "", 10);
    const error = field("Last_IO_Error") || field("Last_SQL_Error") || null;
    return {
        following: field("Replica_IO_Running") === "Yes" && field("Replica_SQL_Running") === "Yes",
        lagSeconds: Number.isFinite(lag) ? lag : null,
        error: error ? error.slice(0, 300) : null
    };
}
