/** An account to sign in with, or none - the localhost exception, which lets a
 *  member with no users yet be initiated and given its first one. */
export interface MongoAuth {
    readonly username: string;
    readonly password: string;
}

/** `mongosh` against the member it runs in, signed in or not. */
function mongosh(auth: MongoAuth | null, script: string): string[] {
    return [
        "mongosh",
        "--quiet",
        ...(auth ? ["-u", auth.username, "-p", auth.password, "--authenticationDatabase", "admin"] : []),
        "--eval",
        script
    ];
}

/** Whether a member answers at all. `ping` needs no account, so it answers on a
 *  member no user has been created on yet as well as on one that has. */
export function mongoPingCommand(): MaintenanceCommand {
    return { argv: mongosh(null, "db.adminCommand({ ping: 1 }).ok"), describe: "Waiting for the member" };
}

/** Whether an account signs in on a member - false while the member still has
 *  no users, which is when the localhost exception applies instead. */
export function mongoSignInCommand(auth: MongoAuth): MaintenanceCommand {
    return { argv: mongosh(auth, "db.runCommand({ connectionStatus: 1 }).ok"), describe: "Signing in" };
}

/** What a member is in its set right now, as one word on the last line:
 *  `primary`, `secondary` or `other`. `hello` needs no account. */
export function mongoRoleCommand(): MaintenanceCommand {
    return {
        argv: mongosh(null, 'const h = db.hello(); h.isWritablePrimary ? "primary" : h.secondary ? "secondary" : "other"'),
        describe: "Checking the member"
    };
}

/** The word `mongoRoleCommand` printed. */
export function mongoRoleOf(output: string): "primary" | "secondary" | "other" {
    const line = output.trim().split(/\r?\n/).at(-1)?.trim();
    return line === "primary" || line === "secondary" ? line : "other";
}

/**
 * Initiate a replica set with all its members, once, from its first member.
 *
 * The first member is given priority 2 and the others 1, so whenever it is
 * healthy it is the primary: it is the container every maintenance step and
 * every database created inside the instance runs in, and those write.
 *
 * Idempotent, like `mongoInitiateCommand`: a set that is already initiated
 * answers its status instead, and so does one somebody initiated in between.
 * Under the localhost exception `replSetInitiate` and `replSetGetStatus` are
 * both allowed, which is what lets this run before any user exists.
 */
export function mongoSetInitiateCommand(auth: MongoAuth | null, set: MongoSet): MaintenanceCommand {
    for (const host of set.hosts) checkHost(host);
    if (!/^[A-Za-z0-9_-]+$/.test(set.name)) throw new Error("A replica set name is a plain word");
    const members = set.hosts
        .map((host, index) => `{ _id: ${index}, host: ${JSON.stringify(`${host}:${MONGO_PORT}`)}, priority: ${index === 0 ? 2 : 1} }`)
        .join(", ");
    const config = `{ _id: ${JSON.stringify(set.name)}${set.configsvr ? ", configsvr: true" : ""}, members: [${members}] }`;
    const script = `try { rs.status().ok } catch (error) { try { rs.initiate(${config}).ok } catch (again) { if (again.codeName !== "AlreadyInitialized") throw again; 1 } }`;
    return { argv: mongosh(auth, script), describe: `Starting the replica set ${set.name}` };
}

/**
 * Give a member with no users its first one, through the localhost exception:
 * the root account the instance's credentials name. On the router it lands on
 * the config servers and is the cluster's; on a shard it is that shard's own,
 * which the manual asks for so the shard is not left open to anything that can
 * reach its localhost.
 */
export function mongoCreateRootCommand(auth: MongoAuth, where: string): MaintenanceCommand {
    const user = `{ user: ${JSON.stringify(auth.username)}, pwd: ${JSON.stringify(auth.password)}, roles: [{ role: "root", db: "admin" }] }`;
    return {
        argv: mongosh(null, `db.getSiblingDB("admin").createUser(${user}).ok`),
        describe: `Creating the administrative account on ${where}`
    };
}

/**
 * Add every shard the router does not list yet, by its seed list. Asked through
 * `listShards`, whose `host` is `<set>/<members>`, so a shard added on an
 * earlier run - or by a run that stopped half way - is not added twice.
 */
export function mongoAddShardsCommand(auth: MongoAuth, shards: readonly MongoSet[]): MaintenanceCommand {
    const seeds = JSON.stringify(shards.map(seedList));
    const script = [
        'const listed = db.adminCommand({ listShards: 1 }).shards.map((shard) => shard.host.split("/")[0])',
        `for (const seed of ${seeds}) { if (!listed.includes(seed.split("/")[0])) sh.addShard(seed) }`,
        "1"
    ].join("; ");
    return { argv: mongosh(auth, script), describe: "Adding the shards" };
}

/** Ask a primary to step down, so the member it runs in can be restarted
 *  without taking writes down with it. */
export function mongoStepDownCommand(auth: MongoAuth): MaintenanceCommand {
    return { argv: mongosh(auth, "rs.stepDown().ok"), describe: "Handing the primary over" };
}

/** The feature compatibility version a set runs at, as MongoDB prints it: `7.0`. */
export function mongoReadFcvCommand(auth: MongoAuth): MaintenanceCommand {
    return {
        argv: mongosh(auth, "db.adminCommand({ getParameter: 1, featureCompatibilityVersion: 1 }).featureCompatibilityVersion.version"),
        describe: "Reading the feature compatibility version"
    };
}

/** A major version's feature compatibility version: `8` is `8.0`. */
export function fcvOf(version: string): string {
    const major = Number.parseInt(version, 10);
    if (!Number.isInteger(major) || major < 1) throw new Error("A version starts with its major number");
    return `${major}.0`;
}

/**
 * Raise (or settle) the feature compatibility version. From 7.0 the command
 * refuses to run without `confirm: true`; 6.0 does not know the field.
 */
export function mongoSetFcvCommand(auth: MongoAuth, version: string): MaintenanceCommand {
    const fcv = fcvOf(version);
    const confirm = Number.parseInt(fcv, 10) >= 7 ? ", confirm: true" : "";
    return {
        argv: mongosh(auth, `db.adminCommand({ setFeatureCompatibilityVersion: ${JSON.stringify(fcv)}${confirm} }).ok`),
        describe: `Setting the feature compatibility version to ${fcv}`
    };
}

/**
 * The majors a rolling upgrade passes through, in order: every offered version
 * newer than `current` up to `target`. MongoDB moves a replica set one major at
 * a time - 6.0 to 8.0 is 6.0 to 7.0, then 7.0 to 8.0 - and the offered versions
 * are consecutive majors, so these are exactly those steps.
 */
export function rollingPath(offered: readonly string[], current: string, target: string): string[] {
    const major = (value: string) => Number.parseInt(value, 10);
    return [...offered]
        .filter((version) => major(version) > major(current) && major(version) <= major(target))
        .sort((a, b) => major(a) - major(b));
}

/** Each member of a set as `rs.status()` sees it. */
export function mongoSetStatusCommand(auth: MongoAuth | null): MaintenanceCommand {
    return {
        argv: mongosh(auth, "JSON.stringify(rs.status().members.map((m) => ({ name: m.name, state: m.stateStr, health: m.health })))"),
        describe: "Reading the replica set's state"
    };
}

const memberStatusSchema = z.array(
    z.object({ name: z.string().max(300), state: z.string().max(40), health: z.number() })
).max(64);

/** The members `mongoSetStatusCommand` printed, or null for anything else - it
 *  is a container's output, so it is parsed as untrusted. */
export function parseSetStatus(output: string): { name: string; state: string; healthy: boolean }[] | null {
    const line = output.trim().split(/\r?\n/).at(-1) ?? "";
    let raw: unknown;
    try {
        raw = JSON.parse(line);
    } catch {
        return null;
    }
    const parsed = memberStatusSchema.safeParse(raw);
    if (!parsed.success) return null;
    return parsed.data.map((member) => ({
        name: member.name.replace(/:\d+$/, ""),
        state: member.state,
        healthy: member.health === 1
    }));
}

