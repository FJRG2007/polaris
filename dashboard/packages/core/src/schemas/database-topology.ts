/**
 * The command a MongoDB member of a replica set or a sharded cluster starts with.
 *
 * It writes the cluster's key from `MONGO_KEY_ENV` to `MONGO_CLUSTER_KEYFILE`,
 * owned by `mongodb` with mode 400 ("the keyfile must not have group or world
 * permissions"), drops the variable, and hands over to the image's entrypoint -
 * which starts the program as the `mongodb` user. `--keyFile` implies `--auth`.
 *
 * - a replica set member: `mongod --replSet rs0 --bind_ip_all`;
 * - a config server: `mongod --configsvr --replSet cfg`, with `--dbpath
 *   /data/db` because the image otherwise gives a config server
 *   `/data/configdb`, which is not where its volume is;
 * - a shard member: `mongod --shardsvr --replSet shardN`;
 * - the router: `mongos --configdb cfg/<config members>`.
 *
 * `--port 27017` is given to config servers and shard members, whose defaults
 * are 27019 and 27018, so every member of every layout is reached on one port.
 *
 * One line, for the reason `mongoReplicaSetCommand` gives.
 */
export function mongoMemberCommand(member: TopologyMember, topology: DbTopology, name: string): string[] {
    let program: string[];
    if (member.role === "router") {
        const config = mongoSets(topology, name).find((set) => set.configsvr);
        if (!config) throw new Error("A router needs a config server replica set");
        program = ["mongos", "--configdb", seedList(config), "--port", String(MONGO_PORT), "--bind_ip_all"];
    } else if (member.role === "config") {
        program = ["mongod", "--configsvr", "--replSet", setOf(member), "--port", String(MONGO_PORT), "--dbpath", "/data/db", "--bind_ip_all"];
    } else if (member.role === "shard") {
        program = ["mongod", "--shardsvr", "--replSet", setOf(member), "--port", String(MONGO_PORT), "--bind_ip_all"];
    } else if (member.role === "member") {
        program = ["mongod", "--replSet", setOf(member), "--bind_ip_all"];
    } else {
        throw new Error(`A ${member.role} is not a MongoDB member`);
    }
    const script = [
        "umask 077",
        `printf '%s' "$${MONGO_KEY_ENV}" > ${MONGO_CLUSTER_KEYFILE}`,
        `chown mongodb:mongodb ${MONGO_CLUSTER_KEYFILE}`,
        `chmod 400 ${MONGO_CLUSTER_KEYFILE}`,
        `unset ${MONGO_KEY_ENV}`,
        `exec docker-entrypoint.sh ${program.join(" ")} --keyFile ${MONGO_CLUSTER_KEYFILE}`
    ].join(" && ");
    return ["sh", "-c", script];
}

function setOf(member: TopologyMember): string {
    if (!member.set || !/^[A-Za-z0-9_-]+$/.test(member.set)) throw new Error("A member belongs to a named replica set");
    return member.set;
}

/**
 * A new cluster key: 384 random bytes as hexadecimal - 768 characters, inside
 * the 6 to 1024 a key may have, and every one of them in the base64 set the
 * manual allows. Generated by the caller from a CSPRNG and passed in here, so
 * this module stays pure; this only checks what it was given is a usable key.
 */
export function isClusterKey(value: unknown): value is string {
    return typeof value === "string" && /^[0-9a-f]{64,1024}$/.test(value);
}

