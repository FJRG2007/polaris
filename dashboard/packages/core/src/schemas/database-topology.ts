/**
 * A database laid out over several containers: a MongoDB replica set, a MongoDB
 * sharded cluster, a MySQL primary with read replicas. Which containers there
 * are and what they are called, the command each one starts with, and the steps
 * that join them once they answer.
 *
 * Pure, like `database-maintenance`: everything here returns names and argument
 * vectors and runs nothing, so the exact commands a layout produces are read in
 * a test. Every host that reaches a script is a container name checked against
 * `CONTAINER_NAME`, and every string that reaches JavaScript or SQL is written
 * as a JSON or SQL literal, never spliced in raw.
 *
 * The MongoDB commands follow the manual's own procedures - "Deploy a
 * Self-Managed Replica Set With Keyfile Authentication" and "Deploy a
 * Self-Managed Sharded Cluster with Keyfile Authentication" - and the MySQL
 * ones "Setting Up Replication Using GTIDs" and `CHANGE REPLICATION SOURCE TO`
 * in the 8.4 manual.
 */

import { z } from "zod";
import type { DbTopology } from "./database.js";
import { MONGO_REPLICA_SET, type MaintenanceCommand } from "./database-maintenance.js";

/** A name docker gives a container and its network answers to. */
const CONTAINER_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$/;

/** The longest container name docker (and a DNS label) will take. */
const MAX_NAME = 63;

/** Port every member listens on, whatever its role - see `mongoMemberCommand`. */
export const MONGO_PORT = 27017;
export const MYSQL_PORT = 3306;

/** The config server replica set's name, inside one cluster. */
export const MONGO_CONFIG_SET = "cfg";

/** Members of a config server replica set and of each shard. */
export const MONGO_CLUSTER_SET_SIZE = 3;

/**
 * The environment variable a MongoDB member is handed its key in.
 *
 * The key the members authenticate each other with is generated by Polaris and
 * kept with the instance's other credentials, encrypted. It is a single line of
 * hexadecimal digits - no line break, no control character - so it can travel
 * as an environment value; the member's command writes it to a file owned by
 * the server's user with mode 400, which is what `--keyFile` reads, and unsets
 * the variable before the server starts.
 */
export const MONGO_KEY_ENV = "POLARIS_MONGO_KEY";

/** Where each member's command writes the key. Outside the data volume, so it is
 *  written again from the stored key on every start and never goes stale. */
export const MONGO_CLUSTER_KEYFILE = "/etc/polaris-mongo.key";

/** The account read replicas sign in to their primary with. */
export const MYSQL_REPLICATION_USER = "polaris_replica";

/**
 * Why nothing takes a copy of a sharded cluster yet. A dump through the router
 * while the balancer moves chunks can miss documents or repeat them; the
 * consistent copy the manual describes stops the balancer and dumps every shard
 * and the config servers together, and restoring it is a procedure of its own.
 * Refused, and said on screen, rather than taken inconsistently.
 */
export const SHARDED_DUMP_REFUSAL =
    "Copies of a sharded cluster are not offered yet. A consistent one needs the balancer stopped and every shard and the config servers copied together, and a copy taken through the router while data moves between shards can miss documents or repeat them.";

/** Why a sharded cluster's version is not changed by Polaris yet. */
export const SHARDED_UPGRADE_REFUSAL =
    "Version changes are not offered for a sharded cluster yet: its config servers, shards and router have to move in a set order with the balancer stopped.";

/** What a member of a multi-container instance is there for. */
export type MemberRole = "member" | "config" | "shard" | "router" | "primary" | "replica";

/** One container of an instance laid out over several. */
export interface TopologyMember {
    /** Container name - also the name the others reach it by. */
    readonly name: string;
    readonly role: MemberRole;
    /** The replica set it belongs to (MongoDB). */
    readonly set: string | null;
    /** What its data volume's name ends in, after the instance's own volume
     *  name; null for a member that keeps nothing (the router). The first
     *  member's is empty: it keeps the volume a single instance would have. */
    readonly volumeSuffix: string | null;
}

/** A MongoDB replica set: its name and its members' container names, the
 *  first of which is initiated from and preferred as primary. */
export interface MongoSet {
    readonly name: string;
    readonly hosts: readonly string[];
    /** A config server replica set is initiated with `configsvr: true`. */
    readonly configsvr?: boolean;
}

/**
 * A member's container name: the instance's own with a suffix, cut to fit.
 * What is cut is the middle - the instance's name ends in a hash of its id,
 * and that hash is what keeps two instances' members from sharing a name.
 */
export function memberName(name: string, suffix: string): string {
    if (name.length + suffix.length <= MAX_NAME) return `${name}${suffix}`;
    const cut = name.lastIndexOf("-");
    const tail = cut > 0 ? name.slice(cut) : "";
    return `${name.slice(0, MAX_NAME - suffix.length - tail.length)}${tail}${suffix}`;
}

/**
 * Every container of an instance, the first being the one the instance's own
 * name belongs to - what applications and every maintenance step reach:
 *
 * - a replica set's first member, preferred as its primary;
 * - a sharded cluster's router, which is what clients connect to;
 * - a MySQL primary.
 *
 * A single instance is its one container.
 */
export function topologyMembers(topology: DbTopology, name: string): TopologyMember[] {
    switch (topology.kind) {
        case "replicaSet":
            return Array.from({ length: topology.members }, (_, index) => ({
                name: index === 0 ? name : memberName(name, `-m${index + 1}`),
                role: "member" as const,
                set: MONGO_REPLICA_SET,
                volumeSuffix: index === 0 ? "" : `-m${index + 1}`
            }));
        case "sharded":
            return [
                { name, role: "router", set: null, volumeSuffix: null },
                ...Array.from({ length: MONGO_CLUSTER_SET_SIZE }, (_, index) => ({
                    name: memberName(name, `-cfg${index + 1}`),
                    role: "config" as const,
                    set: MONGO_CONFIG_SET,
                    volumeSuffix: `-cfg${index + 1}`
                })),
                ...Array.from({ length: topology.shards }, (_, shard) =>
                    Array.from({ length: MONGO_CLUSTER_SET_SIZE }, (_, index) => ({
                        name: memberName(name, `-sh${shard + 1}-${index + 1}`),
                        role: "shard" as const,
                        set: shardSetName(shard),
                        volumeSuffix: `-sh${shard + 1}-${index + 1}`
                    }))
                ).flat()
            ];
        case "replicas":
            return [
                { name, role: "primary", set: null, volumeSuffix: "" },
                ...Array.from({ length: topology.replicas }, (_, index) => ({
                    name: memberName(name, `-replica${index + 1}`),
                    role: "replica" as const,
                    set: null,
                    volumeSuffix: `-replica${index + 1}`
                }))
            ];
        default:
            return [{ name, role: "primary", set: null, volumeSuffix: "" }];
    }
}

/** A shard's replica set name, by its position. */
function shardSetName(index: number): string {
    return `shard${index + 1}`;
}

/** The replica sets of a MongoDB layout, config servers first. */
export function mongoSets(topology: DbTopology, name: string): MongoSet[] {
    const members = topologyMembers(topology, name);
    const hostsOf = (set: string) => members.filter((member) => member.set === set).map((member) => member.name);
    if (topology.kind === "replicaSet") return [{ name: MONGO_REPLICA_SET, hosts: hostsOf(MONGO_REPLICA_SET) }];
    if (topology.kind !== "sharded") return [];
    return [
        { name: MONGO_CONFIG_SET, hosts: hostsOf(MONGO_CONFIG_SET), configsvr: true },
        ...Array.from({ length: topology.shards }, (_, index) => ({ name: shardSetName(index), hosts: hostsOf(shardSetName(index)) }))
    ];
}

/** A replica set as a seed list - `rs0/a:27017,b:27017` - the form `sh.addShard`,
 *  `mongos --configdb` and the database tools' `--host` read. */
export function seedList(set: MongoSet): string {
    for (const host of set.hosts) checkHost(host);
    return `${set.name}/${set.hosts.map((host) => `${host}:${MONGO_PORT}`).join(",")}`;
}

function checkHost(host: string): void {
    if (!CONTAINER_NAME.test(host)) throw new Error("A member host is a container name");
}

/** How clients reach a layout: the hosts a connection string lists, the replica
 *  set it names, and - for MySQL with replicas - the name the replicas share. */
export function topologyAddress(
    topology: DbTopology,
    name: string
): { hosts: string[]; replicaSet: string | null; readHost: string | null } {
    if (topology.kind === "replicaSet") {
        return { hosts: topologyMembers(topology, name).map((member) => member.name), replicaSet: MONGO_REPLICA_SET, readHost: null };
    }
    if (topology.kind === "replicas") return { hosts: [name], replicaSet: null, readHost: readHostName(name) };
    // A sharded cluster is reached through its router alone, like one server.
    return { hosts: [name], replicaSet: null, readHost: null };
}

/**
 * The name every read replica answers to beside its own. Docker's resolver
 * answers a name several containers share with all of their addresses, so a
 * client reading from it is spread across the replicas without a balancer.
 */
export function readHostName(name: string): string {
    return memberName(name, "-read");
}

