    var lang = String(navigator.language || "en").toLowerCase().indexOf("es") === 0 ? "es" : "en";

    /** The string for `key`, with each `{name}` replaced by `values[name]`. */
    function t(key, values) {
        var text = TEXT[lang][key];
        if (text === undefined) text = TEXT.en[key];
        if (text === undefined) text = key;
        Object.keys(values || {}).forEach(function (name) {
            text = text.split(`{${name}}`).join(String(values[name]));
        });
        return text;
    }

    var ATTRIBUTES = { "data-text-placeholder": "placeholder", "data-text-label": "aria-label", "data-text-title": "title" };

    /** Put the page's own strings in its language. */
    function apply(root) {
        document.documentElement.lang = lang === "es" ? "es-ES" : "en";
        root.querySelectorAll("[data-text]").forEach(function (element) {
            element.textContent = t(element.getAttribute("data-text"));
        });
        Object.keys(ATTRIBUTES).forEach(function (attribute) {
            root.querySelectorAll(`[${attribute}]`).forEach(function (element) {
                element.setAttribute(ATTRIBUTES[attribute], t(element.getAttribute(attribute)));
            });
        });
        var title = document.querySelector("title[data-text-window]");
        if (title) document.title = t(title.getAttribute("data-text-window"));
    }

    window.polarisText = Object.freeze({ lang: lang, t: t, apply: apply });
    apply(document);
