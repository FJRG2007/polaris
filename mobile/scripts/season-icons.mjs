/**
 * The phone apps' launcher icons for each season, drawn from the same mark and
 * accessory geometry the tab icon and the desktop app use
 * (`dashboard/packages/core/src/season-mark.ts`), so the three cannot drift.
 *
 * Writes, for every season:
 * - Android: a vector foreground on the adaptive icon's 108 dp canvas and the
 *   adaptive icon around it, the star at the size the shipped foreground has it.
 * - iOS: a 1024 px alternate app icon in its own icon set, the star at the size
 *   the shipped AppIcon has it.
 *
 * Run from the repository root after changing the mark or an accessory:
 *   node mobile/scripts/season-icons.mjs
 * It needs Node with type stripping (22.18+) and the dashboard's dependencies
 * installed, since it rasterizes the iOS icons with sharp.
 */

import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import * as mark from "../../dashboard/packages/core/src/season-mark.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const sharp = createRequire(join(root, "dashboard", "apps", "web", "package.json"))("sharp");

/** Android resource and iOS icon names, one per season. */
const NAMES = {
    halloween: { android: "halloween", ios: "AppIcon-Halloween" },
    winter: { android: "winter", ios: "AppIcon-Winter" },
    newYear: { android: "new_year", ios: "AppIcon-NewYear" },
    lunarNewYear: { android: "lunar_new_year", ios: "AppIcon-LunarNewYear" }
};

/**
 * Where the mark's 32-unit grid sits on each canvas, measured from the shipped
 * icons so a dressed icon's star is exactly where the plain one's is: on
 * Android the star spans 51.5 dp of the 108 dp foreground, on iOS 481 px of
 * the 1024 px icon.
 */
const ANDROID_SCALE = 51.5 / 26;
const ANDROID_OFFSET = 54 - 16 * ANDROID_SCALE;
const IOS_SCALE = 481 / 26;
const IOS_OFFSET = 512 - 16 * IOS_SCALE;

const res = join(root, "mobile", "android", "app", "src", "main", "res");
const assets = join(root, "mobile", "ios", "Polaris", "Assets.xcassets");

function round(value) {
    return Number(value.toFixed(4));
}

/** The star and the season's accessory, in paint order. */
function shapes(season) {
    return [{ d: mark.MARK_STAR, fill: mark.MARK_FOREGROUND }, ...mark.SEASON_MARK_ACCESSORIES[season]];
}

function androidForeground(season) {
    const paths = shapes(season)
        .map((shape) => `        <path\n            android:fillColor="${shape.fill}"\n            android:pathData="${shape.d}" />`)
        .join("\n");
    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/season-icons.mjs from the mark in @polaris/core. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="${round(ANDROID_SCALE)}"
        android:scaleY="${round(ANDROID_SCALE)}"
        android:translateX="${round(ANDROID_OFFSET)}"
        android:translateY="${round(ANDROID_OFFSET)}">
${paths}
    </group>
</vector>
`;
}

function androidAdaptive(name) {
    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/season-icons.mjs. The themed (monochrome) icon stays the plain star. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground_${name}" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`;
}

/** The iOS icon as SVG: full bleed, since the system rounds the corners itself. */
function iosSvg(season) {
    const paths = shapes(season).map((shape) => `<path d="${shape.d}" fill="${shape.fill}"/>`).join("");
    const group = `<g transform="translate(${round(IOS_OFFSET)} ${round(IOS_OFFSET)}) scale(${round(IOS_SCALE)})">${paths}</g>`;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><rect width="1024" height="1024" fill="${mark.MARK_BACKGROUND}"/>${group}</svg>`;
}

const IOS_CONTENTS = `{
  "images" : [
    { "filename" : "icon-1024.png", "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" }
  ],
  "info" : { "author" : "xcode", "version" : 1 }
}
`;

for (const [season, name] of Object.entries(NAMES)) {
    mkdirSync(join(res, "drawable"), { recursive: true });
    mkdirSync(join(res, "mipmap-anydpi-v26"), { recursive: true });
    writeFileSync(join(res, "drawable", `ic_launcher_foreground_${name.android}.xml`), androidForeground(season));
    writeFileSync(join(res, "mipmap-anydpi-v26", `ic_launcher_${name.android}.xml`), androidAdaptive(name.android));

    const set = join(assets, `${name.ios}.appiconset`);
    mkdirSync(set, { recursive: true });
    writeFileSync(join(set, "Contents.json"), IOS_CONTENTS);
    // No alpha channel: the asset compiler and the App Store refuse a transparent app icon.
    await sharp(Buffer.from(iosSvg(season)))
        .flatten({ background: mark.MARK_BACKGROUND })
        .removeAlpha()
        .png()
        .toFile(join(set, "icon-1024.png"));
}
